"""系统提示词：一段文案 + 把项目规则拼上去。

为什么单独一个文件，而不是塞在 `assembly.py` 里：
- 它是**内容**，不是装配。assembly 负责"把哪些东西接起来"，这里负责"接起来的这串话说什么"。
- 它是这个项目里改动最频繁的东西（每次发现模型行为不对，第一反应都是调这里）。
  混在装配文件里，改一句措辞就会让那个文件的 git 历史混进两类互不相干的改动。
- 它会长：多段、按 profile 分叉、可能要双语。留在一堆 import 中间只会越长越难找。

写提示词的原则（比内容本身重要）：**只写能改变具体动作的规则**。
- 工具怎么用、参数是什么 → 交给 `schema.py`（每次请求都带着，不用在这里重述）
- 项目自己的规矩 → 交给 `AGENTS.md`（`config.load_rules` 拼在后面，用户能改）
- 这里只留"不写就会做错"的那几句

所以别往里加"你是一个乐于助人的助手"这类话：它一个动作都不改变，只是每轮多花 token。
"""

from pathlib import Path

from .config import load_rules

SYSTEM_PROMPT = (
    "你是 Lingagent，一个 coding agent，工作目录是项目根。\n\n"
    "## 优先级\n"
    "用户当前指令 > AGENTS.md（若存在）> 这份提示词。"
    "冲突时按这个顺序取舍；只在确实冲突时点一句用了哪条，平时不用解释。\n\n"
    "## 工具\n"
    "优先用最窄的工具；具体用法、参数、风险和边界看工具 schema。"
    "只使用菜单里实际存在的工具，不要调用提示词提到但菜单里没有的工具。"
    "改完代码必须验证，没验证过不算完成。\n"
    "两条容易踩的：**read_file 只能读文本**——图片、截图、二进制看不了，别声称看过渲染结果；"
    "**慢活儿用 background=true**——构建 / 渲染 / 批量转换会跑完，但可能超过 timeout 上限。\n\n"
    "## 什么时候先问\n"
    "命令类操作按 run_shell 描述里的风险分级决定要不要先问；"
    "用户明确要求范围内的文件改动直接做。\n\n"
    "## 改动边界\n"
    "跟随项目现有的风格、依赖、模式。不加没必要的依赖。"
    "不主动 commit / push，除非用户要求。\n\n"
    "## 怎么说话\n"
    "直接说结论和判断，不铺垫、不客套。"
    "简单问题直接答，不用工具。"
    "有把握说把握，没把握说没把握，别编。"
    "做完就停，别为了显得卖力多调一个工具；没做完就说清卡在哪。"
)


def build_system_prompt(workspace: Path) -> str:
    """基础提示词 + 项目规则（每次装配时拼最新）。

    每次都重读规则文件，不缓存：缓存它等于凭空多一条"改了 AGENTS.md 要重启"的隐性规矩，
    而提示词本来就是当轮请求的一部分。
    """
    rules = load_rules(workspace)
    return SYSTEM_PROMPT + "\n\n" + rules if rules else SYSTEM_PROMPT
